package com.wyx.travelagent.planning.validation;

/**
 * 业务问题：区分阻止后续阶段的硬错误与可以随方案展示的不确定风险。
 * 输入由确定性规则产生，输出为稳定严重级别；本类型不访问模型、数据库、缓存、文件或网络，不处理认证。
 * 任务十提供事实，任务十二据事实分类问题，后续编排以 ERROR 决定是否继续；本类型不负责生成、展示或自动修正。
 */
public enum IssueSeverity {
    /** 已违反确定约束，方案不得进入下一阶段。 */
    ERROR,
    /** 事实缺失或存在风险，方案可继续但必须显式展示。 */
    WARNING
}
