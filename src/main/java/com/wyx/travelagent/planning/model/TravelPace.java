package com.wyx.travelagent.planning.model;

/**
 * 业务问题：以稳定枚举表达每日活动密度偏好，避免后续规划解释任意节奏字符串。
 * 输入由需求校验器解析外部文本，输出是节奏枚举；本类型不访问数据库、模型、缓存、文件或网络，不处理认证。
 * 任务十负责工具数据，任务十二负责容量与冲突校验，后续编排消费节奏；本类型不负责解析、认证、偏好存储或生成行程。
 */
public enum TravelPace {
    /** 宽松节奏，预留较多休息时间。 */
    RELAXED,
    /** 适中节奏，在覆盖度和休息之间平衡。 */
    MODERATE,
    /** 紧凑节奏，单位时间安排更多活动。 */
    COMPACT
}
