package com.wyx.travelagent.planning.model;

/**
 * 业务问题：以稳定枚举表达可参与偏好补全的旅行兴趣，避免任意标签进入规划。
 * 输入由需求校验器解析外部兴趣文本，输出是兴趣枚举；本类型不访问数据库、模型、缓存、文件或网络，不处理认证。
 * 任务十负责工具数据，任务十二负责行程合法性，后续编排消费兴趣；本类型不负责解析、偏好持久化、认证或生成行程。
 */
public enum TravelInterest {
    /** 地方美食与餐饮体验。 */
    FOOD,
    /** 历史遗迹、博物馆与人文内容。 */
    HISTORY,
    /** 自然风景与户外体验。 */
    NATURE,
    /** 摄影取景与视觉体验。 */
    PHOTOGRAPHY,
    /** 购物与商业街区体验。 */
    SHOPPING
}
